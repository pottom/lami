/// git needs the user's ssh keys, agent and credential helpers, none of which
/// survive sudo. So these commands refuse root rather than half-working.
pub fn refuse_root(what: &str) -> Result<()> {
    if unsafe { libc::geteuid() } == 0 {
        return Err(Error::Other(format!(
            "`{what}` talks to your git remote, so run it as yourself, not with sudo.\n\
             Under sudo your ssh agent and credential helper are gone, and any file\n\
             git wrote would end up owned by root."
        )));
    }
    Ok(())
}

fn git(dir: Option<&Path>, args: &[&str]) -> Result<std::process::ExitStatus> {
    let mut c = Command::new("git");
    if let Some(d) = dir {
        c.arg("-C").arg(d);
    }
    c.args(args);
    c.status().map_err(|source| Error::Io {
        path: PathBuf::from("git"),
        source,
    })
}

fn git_out(dir: &Path, args: &[&str]) -> Result<String> {
    let out = Command::new("git")
        .arg("-C")
        .arg(dir)
        .args(args)
        .stderr(Stdio::null())
        .output()
        .map_err(|source| Error::Io {
            path: PathBuf::from("git"),
            source,
        })?;
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

fn ok(status: std::process::ExitStatus, what: &str) -> Result<()> {
    if status.success() {
        Ok(())
    } else {
        Err(Error::Other(format!("git {what} failed")))
    }
}

pub fn is_repo(dir: &Path) -> bool {
    dir.join(".git").exists()
}

/// The `origin` URL of a working copy, if it has one.
pub fn remote_url(dir: &Path) -> Option<String> {
    let s = git_out(dir, &["remote", "get-url", "origin"]).ok()?;
    (!s.is_empty()).then_some(s)
}

/// Clone `url` into `dest`. If `dest` is already that same repo, adopt it.
pub fn clone(url: &str, dest: &Path) -> Result<()> {
    if is_repo(dest) {
        match remote_url(dest) {
            Some(u) if same_remote(&u, url) => {
                println!("  already cloned: {}", dest.display());
                return Ok(());
            }
            Some(u) => {
                return Err(Error::Other(format!(
                    "{} is a git repo, but its origin is a different one:\n  \
                     there: {u}\n  wanted: {url}\n\
                     Move it aside, or pass --path to clone somewhere else.",
                    dest.display()
                )))
            }
            None => {
                return Err(Error::Other(format!(
                    "{} is a git repo with no origin remote. Move it aside, or \
                     pass --path to clone somewhere else.",
                    dest.display()
                )))
            }
        }
    }
    if dest.exists() && dest.read_dir().is_ok_and(|mut d| d.next().is_some()) {
        return Err(Error::Other(format!(
            "{} exists and is not empty. Move it aside, or pass --path.",
            dest.display()
        )));
    }
    if let Some(parent) = dest.parent() {
        std::fs::create_dir_all(parent).map_err(|source| Error::Io {
            path: parent.to_path_buf(),
            source,
        })?;
    }
    println!("  git clone {url}");
    ok(
        git(None, &["clone", url, &dest.to_string_lossy()])?,
        "clone",
    )
}

/// Two URLs for the same repository, allowing for a trailing `.git` and a
/// trailing slash. Not an attempt at full URL equivalence -- just enough to
/// keep `github.com/x/y` and `github.com/x/y.git` from looking like a clash.
fn same_remote(a: &str, b: &str) -> bool {
    fn norm(s: &str) -> String {
        s.trim_end_matches('/').trim_end_matches(".git").to_string()
    }
    norm(a) == norm(b)
}

/// Uncommitted changes, in `git status --porcelain` form.
pub fn dirty(dir: &Path) -> Result<Vec<String>> {
    let out = git_out(dir, &["status", "--porcelain"])?;
    Ok(out
        .lines()
        .filter(|l| !l.trim().is_empty())
        .map(str::to_string)
        .collect())
}

/// Fast-forward the working copy to its remote.
///
/// `--ff-only`: a config repo should never grow a merge commit behind your
/// back. If the histories have diverged, that is a real conflict and you want
/// to see it in git, not have it resolved by a tool.
pub fn pull(dir: &Path) -> Result<()> {
    let d = dirty(dir)?;
    if !d.is_empty() {
        println!(
            "{}",
            color::changed(&format!(
                "  {} uncommitted change(s) -- pulling anyway, they stay put:",
                d.len()
            ))
        );
        for l in d.iter().take(10) {
            println!("    {l}");
        }
    }
    ok(git(Some(dir), &["pull", "--ff-only"])?, "pull")
}

/// Commit everything and push.
pub fn push(dir: &Path, message: Option<&str>, host: &str) -> Result<bool> {
    let d = dirty(dir)?;
    if d.is_empty() {
        // Still push: there may be commits made earlier that never went out.
        let ahead = git_out(dir, &["rev-list", "--count", "@{u}..HEAD"]).unwrap_or_default();
        if ahead == "0" {
            println!("  nothing to push -- the repo matches its remote.");
            return Ok(false);
        }
        println!("  {ahead} commit(s) to push");
        ok(git(Some(dir), &["push"])?, "push")?;
        return Ok(true);
    }

    println!("  staging {} change(s)", d.len());
    for l in d.iter().take(20) {
        println!("    {l}");
    }
    if d.len() > 20 {
        println!("    ... and {} more", d.len() - 20);
    }

    ok(git(Some(dir), &["add", "-A"])?, "add")?;
    let default = format!("{host}: config update");
    let msg = message.unwrap_or(&default);
    ok(git(Some(dir), &["commit", "-m", msg])?, "commit")?;
    ok(git(Some(dir), &["push"])?, "push")?;
    Ok(true)
}

/// One line describing where the repo stands, for `lami show`.
pub fn summary(dir: &Path) -> Option<String> {
    if !is_repo(dir) {
        return None;
    }
    let branch = git_out(dir, &["rev-parse", "--abbrev-ref", "HEAD"]).ok()?;
    let n = dirty(dir).map(|v| v.len()).unwrap_or(0);
    let state = if n == 0 {
        "clean".to_string()
    } else {
        format!("{n} uncommitted")
    };
    Some(match remote_url(dir) {
        Some(u) => format!("{u} [{branch}, {state}]"),
        None => format!("[{branch}, {state}] (no remote)"),
    })
}
