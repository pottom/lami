//! The config repo: where it lives, and keeping it in sync with its remote.
//!
//! The config is a git repository, and lami needs to find it before it can
//! parse anything. That pointer cannot live inside the repo itself, so it
//! lives beside it in a small file:
//!
//! ```kdl
//! // ~/.config/lami.kdl
//! repo "git@github.com:you/lami-config.git"
//! path "~/Projects/lami-config"
//! ```
//!
//! Both lines are optional and both have a command line equivalent
//! (`--repo`, `--config-dir`). With neither, lami falls back to
//! `~/.config/lami`.
//!
//! git is shelled out to, for the same reason pacman is: an in-process git
//! library would tie us to its idea of ssh, credential helpers and signing,
//! all of which the user has already configured for the `git` they use.

use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use crate::color;
use crate::error::{Error, Result};

/// The machine-local pointer to the config repo.
#[derive(Debug, Default)]
pub struct Pointer {
    /// Remote URL, if one was recorded.
    pub repo: Option<String>,
    /// Where the working copy lives on this machine.
    pub path: Option<PathBuf>,
}

/// Where the pointer file lives: `$XDG_CONFIG_HOME/lami.kdl`, else
/// `~/.config/lami.kdl`.
///
/// Deliberately a file next to the `lami/` directory rather than inside it:
/// the directory may be the repo, or may not exist yet.
pub fn pointer_path(home: &Path) -> PathBuf {
    match std::env::var("XDG_CONFIG_HOME") {
        Ok(x) if !x.is_empty() => PathBuf::from(x).join("lami.kdl"),
        _ => home.join(".config").join("lami.kdl"),
    }
}

impl Pointer {
    pub fn load(home: &Path) -> Result<Pointer> {
        let file = pointer_path(home);
        if !file.is_file() {
            return Ok(Pointer::default());
        }
        let src = std::fs::read_to_string(&file).map_err(|source| Error::Io {
            path: file.clone(),
            source,
        })?;
        let doc: kdl::KdlDocument = src.parse()?;
        let mut p = Pointer::default();
        for node in doc.nodes() {
            let val = node
                .entries()
                .iter()
                .find(|e| e.name().is_none())
                .and_then(|e| e.value().as_string())
                .map(str::to_string);
            match (node.name().value(), val) {
                ("repo", Some(v)) => p.repo = Some(v),
                ("path", Some(v)) => p.path = Some(crate::config::expand_home(&v, home)),
                _ => {}
            }
        }
        Ok(p)
    }

    /// Write the pointer file, preserving nothing: it has two lines and is
    /// generated by `lami clone`.
    pub fn save(&self, home: &Path) -> Result<PathBuf> {
        let file = pointer_path(home);
        if let Some(parent) = file.parent() {
            std::fs::create_dir_all(parent).map_err(|source| Error::Io {
                path: parent.to_path_buf(),
                source,
            })?;
        }
        let mut s = String::from(
            "// Where lami finds your config repo. Written by `lami clone`;\n\
             // edit it freely, or override with --repo / --config-dir.\n",
        );
        if let Some(r) = &self.repo {
            s.push_str(&format!("repo {}\n", quote(r)));
        }
        if let Some(p) = &self.path {
            s.push_str(&format!("path {}\n", quote(&tilde(p, home))));
        }
        std::fs::write(&file, s).map_err(|source| Error::Io {
            path: file.clone(),
            source,
        })?;
        Ok(file)
    }
}

fn quote(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

/// Render a path back with `~/` if it is under the home directory, so the
/// pointer file stays readable and portable.
fn tilde(p: &Path, home: &Path) -> String {
    match p.strip_prefix(home) {
        Ok(rest) => format!("~/{}", rest.display()),
        Err(_) => p.display().to_string(),
    }
}

